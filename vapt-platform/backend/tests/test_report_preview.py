def test_render_preview_html_embeds_template_images_as_data_uris():
    """The preview must embed the DMC template's images (logo, cover
    background, etc.) as base64 data URIs so the sandboxed iframe can
    render them without external requests. Stripping images would
    visibly break the cover page."""
    from app.services.reporting.render import render_preview_html
    html = render_preview_html(_make_ctx())
    # Image tags with data: URIs from the template
    data_uri_imgs = re.findall(
        r'<img src="data:image/(?:png|jpeg);base64,[A-Za-z0-9+/=]+"',
        html,
    )
    # The DMC template has 8 images; the cover page is the dominant
    # user-visible one. We don't require all 8 (some may be dropped by
    # mammoth if unreferenced) but at least the logo + cover background
    # must be present.
    assert len(data_uri_imgs) >= 2, (
        f"expected >=2 data: URI images, got {len(data_uri_imgs)}"
    )
    # Total payload must be large enough to actually carry the images
    # (a stripped preview is ~30-40KB; with the 1.4MB cover image
    # embedded the preview is well over 100KB).
    assert len(html.encode("utf-8")) >= 100_000, (
        f"preview payload too small ({len(html)} chars) — images were stripped"
    )


def test_render_preview_html_cover_table_is_first_table_in_body():
    """The DMC template's title page is the first <table> in the docx
    body. The preview must preserve that ordering so the cover page
    (with the logo + client name) renders above the scope and findings
    sections."""
    from app.services.reporting.render import render_preview_html
    html = render_preview_html(_make_ctx())
    body_match = re.search(r"<body[^>]*>(.*)</body>", html, re.DOTALL)
    assert body_match is not None
    body = body_match.group(1)
    first_table = re.search(r"<table.*?</table>", body, re.DOTALL)
    assert first_table is not None
    # The first table must contain the cover-page labels ("For:", "Type:",
    # "From:", "Date:") and the client name + start date.
    first = first_table.group(0)
    assert "For" in first
    assert "Type" in first
    assert "From" in first
    assert "Date" in first
    assert "Acme Corp" in first
