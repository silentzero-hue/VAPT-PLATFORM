def test_render_preview_html_tags_editable_regions():
    """The preview must tag the editable regions so the editor can map
    DOM changes back to the structured draft fields. The narrative is
    wrapped in a <div data-field="exec_summary">; each finding's impact
    and recommendation <td> gets a data-field + data-finding-id."""
    from app.services.reporting.render import _apply_draft, render_preview_html
    # No narrative in the fixture → no exec_summary wrapper
    html0 = render_preview_html(_make_ctx())
    assert 'data-field="exec_summary"' not in html0

    ctx = _make_ctx()
    _apply_draft(ctx, {
        "exec_summary": "My override narrative.\n\nSecond paragraph.",
    })
    html = render_preview_html(ctx)
    assert 'data-field="exec_summary"' in html
    m = re.search(
        r'data-field="exec_summary"[^>]*>(.*?)<h1[^>]*><a[^>]*></a><strong>DETAILED FINDINGS</strong></h1>',
        html, re.DOTALL,
    )
    assert m is not None
    assert "My override narrative." in m.group(1)
    assert "Second paragraph." in m.group(1)

    # Impact and recommendation cells tagged per finding (one per vuln in detailed_findings)
    for fid in ("fid-1", "fid-2"):
        assert f'data-field="finding.impact" data-finding-id="{fid}"' in html
        assert f'data-field="finding.recommendation" data-finding-id="{fid}"' in html


def test_render_preview_html_replaces_dmc_template_literals():
    """The DMC template hardcodes 'Data Management Center', 'DMC', and the
    old test date in prose paragraphs. After rendering with a new
    engagement these must be replaced; the disclaimer brand reference
    and CVE references must NOT be touched."""
    from app.services.reporting.render import render_preview_html
    ctx = _make_ctx()  # client='Acme Corp'
    # Use a different start_date so the new formatted date is clearly
    # distinct from the template's hardcoded "2nd October, 2025".
    ctx["engagement"]["start_date"] = "2025-11-05"
    html = render_preview_html(ctx)

    # Old DMC literals must be gone from the rendered report
    assert "Data Management Center" not in html

    # The template's hardcoded test date is gone (replaced with the new one)
    assert "2nd October, 2025" not in html

    # New engagement's client and formatted start date are present
    assert "Acme Corp" in html
    assert "5th November, 2025" in html

    # The DMC abbreviation in prose is replaced
    # (the template has "DMC's penetration testing", "DMC should also ensure",
    #  and "advisable for DMC to refer" — all should be replaced with "Acme Corp")
    assert "DMC's penetration" not in html
    assert "DMC should also" not in html
    assert "for DMC to refer" not in html

    # The disclaimer is preserved verbatim (brand reference, not engagement-specific)
    assert "This publication has been carefully prepared" in html
    assert "Technovage Solution" in html  # the disclaimer keeps the brand

    # CVE references in finding details are NOT replaced (they live in
    # table cells which are owned by _fill_*, and even in prose the
    # replacement would no-op on CVE refs).
    assert "CVE-2024-1234" in html


def test_replace_template_literals_preserves_paragraph_formatting():
    """The replacement must preserve the paragraph's character formatting
    (bold, etc.) by writing into the first run, not by deleting all
    runs and re-adding."""
    from docx import Document

    from app.services.reporting.render import _replace_template_literals
    from app.services.reporting.render import _resolve_template_path
    template_path = _resolve_template_path()
    assert template_path, "DMC template must be available for this test"
    doc = Document(template_path)
    ctx = _make_ctx()

    # Capture a paragraph's first-run style before replacement
    target = None
    for p in doc.paragraphs:
        if "Data Management Center" in p.text:
            target = p
            break
    assert target is not None
    first_run = target.runs[0]
    bold_before = first_run.bold
    font_size_before = first_run.font.size

    _replace_template_literals(doc, ctx)

    # Same paragraph now has the new client name, not the DMC literal
    assert "Data Management Center" not in target.text
    assert "Acme Corp" in target.text
    # The first run's formatting is preserved
    assert target.runs[0].bold == bold_before
    assert target.runs[0].font.size == font_size_before


